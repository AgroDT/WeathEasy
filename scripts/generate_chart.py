"""Generate Helm values and their Markdown reference from values.schema.json."""

import argparse
import json
from collections.abc import Iterable
from pathlib import Path

import jsonref
import yaml


START = '<!-- VALUES_START -->'
END = '<!-- VALUES_END -->'


def yaml_lines(value: dict) -> list[str]:
    return yaml.safe_dump(value, sort_keys=False, allow_unicode=True, width=100).splitlines()


def render_property(
    name: str,
    schema: dict,
    parents: tuple[int, ...] = (),
) -> tuple[list[str], bool]:
    if id(schema) in parents:
        msg = f'Cyclic schema at {name}'
        raise ValueError(msg)
    parents = (*parents, id(schema))
    description = [f'# {line}' for line in schema.get('description', '').splitlines()]
    if 'default' in schema:
        return description + yaml_lines({name: schema['default']}), True
    if properties := schema.get('properties'):
        children = [render_property(key, child, parents) for key, child in properties.items()]
        active = any(has_default for _, has_default in children)
        lines = [f'{name}:']
        for child_lines, _ in children:
            lines.extend(f'  {line}' for line in child_lines)
        if not active:
            # The entire object is optional when none of its children has a default.
            lines = [f'# {line}' for line in lines]
        return description + lines, active
    # No invented default: a commented key is a placeholder for user configuration.
    return [*description, f'# {yaml_lines({name: None})[0].removesuffix(" null")}'], False


def render_values(root: dict) -> str:
    lines = ['# @generated by scripts/generate_chart.py; edit values.schema.json.', '']
    for name, schema in root['properties'].items():
        lines.extend(render_property(name, schema)[0])
        lines.append('')
    body = '\n'.join(lines).rstrip()
    return f'{body}\n'


def markdown_cell(value: str) -> str:
    return value.replace('|', '&#124;').replace('\n', '<br>')


def render_table(root: dict) -> str:
    rows = ['| Parameter | Type | Default | Description |', '| --- | --- | --- | --- |']

    def walk(properties: dict, prefix: str = '', parents: tuple[int, ...] = ()) -> None:
        for name, schema in properties.items():
            if id(schema) in parents:
                msg = f'Cyclic schema at {prefix}.{name}'
                raise ValueError(msg)
            path = f'{prefix}.{name}' if prefix else name
            # An explicit object default is documented as a whole (like arrays/maps).
            if 'default' not in schema and schema.get('properties'):
                walk(schema['properties'], path, (*parents, id(schema)))
                continue
            kind = schema.get('type', '')
            if isinstance(kind, list):
                kind = ' / '.join(kind)
            default = (
                f'`{json.dumps(schema["default"], ensure_ascii=False, separators=(",", ":"))}`'
                if 'default' in schema
                else '— (commented out)'
            )
            cells = [f'`{path}`', kind, default, schema.get('description', '')]
            rows.append(f'| {" | ".join(markdown_cell(cell) for cell in cells)} |')

    walk(root['properties'])
    return '\n'.join(rows)


def generate(chart: Path) -> Iterable[tuple[Path, str]]:
    with chart.joinpath('values.schema.json').open(encoding='utf-8') as values:
        root = jsonref.replace_refs(
            json.load(values),
            jsonschema=True,
            proxies=False,
            lazy_load=False,
        )
    readme_path = chart / 'README.md'
    readme = readme_path.read_text(encoding='utf-8')
    if readme.count(START) != 1 or readme.count(END) != 1:
        msg = f'{readme_path} must contain exactly one {START}/{END} pair'
        raise ValueError(msg)
    before, rest = readme.split(START, 1)
    _, after = rest.split(END, 1)
    return (
        (chart / 'values.yaml', render_values(root)),
        (readme_path, f'{before}{START}\n\n{render_table(root)}\n\n{END}{after}'),
    )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('chart', type=Path, nargs='?')
    parser.add_argument('--check', action='store_true', help='Check outputs without writing files')
    args = parser.parse_args()
    chart = args.chart or Path(__file__).joinpath('../../charts/weatheasy').resolve()
    try:
        generated = generate(chart)
    except (OSError, ValueError, KeyError, jsonref.JsonRefError) as error:
        parser.exit(2, f'{error}\n')

    ecode = 0
    for path, content in generated:
        if not path.exists() or path.read_text(encoding='utf-8') != content:
            if args.check:
                ecode = 1
                print(f'Out of date: {path}')
            else:
                path.write_text(content, encoding='utf-8', newline='\n')
                print(f'Generated: {path}')
    parser.exit(ecode)


if __name__ == '__main__':
    main()
